import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable {
    case chinese = "zh"
    case english = "en"

    static let defaultsKey = "paperdesk.language"

    var id: String { rawValue }

    var menuTitle: String {
        switch self {
        case .chinese: return "中文"
        case .english: return "English"
        }
    }

    static var current: AppLanguage {
        AppLanguage(rawValue: UserDefaults.standard.string(forKey: defaultsKey) ?? "") ?? .chinese
    }
}

func L(_ chinese: String) -> String {
    guard AppLanguage.current == .english else { return chinese }
    return englishTranslations[chinese] ?? chinese
}

func L(_ chinese: String, _ english: String) -> String {
    AppLanguage.current == .english ? english : chinese
}

