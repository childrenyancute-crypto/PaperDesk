import Foundation

/// Installs the bounded feedback analyst used by PaperDesk reading projects.
///
/// The analyst is intentionally a narrow classifier. Its instructions require
/// it to avoid reading the paper, calling tools, writing files, or producing
/// the answer sent to the user.
enum CodexPaperFeedback {
    static let agentName = "paperdesk-feedback-analyst"

    /// One self-contained AGENTS.md bullet for the main agent's continuation
    /// policy. Keep this as one physical line so it can be embedded in the
    /// managed instruction block without adding another heading or role config.
    static let instructions = "- 当前聊天确实续接一条已知的上一条归档问答时，主 agent 应在准备答复的同时并行派生一个名为 \(agentName) 的子 agent；使用独立上下文，只传上一条用户问题、上一条答复中与本轮相关的摘录和本轮用户原话（previous user question、relevant previous-answer excerpt、current user-authored message）。若用户明确禁止任何子 agent、禁止记录或 no logging，遵从用户；没有可用子 agent 时明确省略 feedback，只有主 agent 已有清楚直接证据时才可自行分类，否则也省略。若支持，派生时使用 `fork_turns=none`；旧接口支持时回退为 `fork_context=false`。分析者只返回 none，或 kind+exact evidence：kind 只能是 unclear（用户明确说没看懂/无法理解）、repeated_question（基本重复上一问题）或 follow_up（明确深化上一答复）；evidence 必须逐字来自当前用户原话且不超过 240 个字符。明确询问并深化上一答复的普通 follow-up 返回 follow_up；只有无关、关系不清、没有信号才返回 none，不要猜测用户不满意；忽略被引用为示例的文字。标签重叠时按 unclear > repeated_question > follow_up 优先。主 agent 应等待并核验分析结果后再归档；仅在分析者确实返回非 none 时，把可选 feedback {kind,evidence} 传给既有 save_discussion，并只在确实使用对应路径时传可选 answer_mode（direct、self_review 或 independent_review）；外部续接沿用已有 previous_discussion_id，PaperDesk 浮动提问遵循项目提示提供的续接上下文，旧 harness 不支持可选字段时按普通归档。不要添加额外写入工具或改变权限。feedback 分析者与已有 paperdesk-answer-reviewer 规则可以并存，但用户明确禁止任何子 agent 时两者都不派生；每个角色最多派生一个。"

    private static let generatedComment = "# paperdesk-managed: \(agentName) v1 (generated by PaperDesk)"
    private static let description = "判断论文问答续问是否重复、深化或明确表示没看懂"
    private static let developerInstructions = "你是 \(agentName)，只负责判断一次当前聊天续问与上一条已归档论文问答的关系。主 agent 只会提供上一条用户问题、上一条答复中与本轮相关的摘录和当前用户原话（previous user question、relevant previous-answer excerpt、current user-authored message）；只使用这些输入，在独立上下文中工作。只返回一行 `none`，或 `kind=<unclear|repeated_question|follow_up>; evidence=<当前用户原话中的确切原文片段>`。unclear 只用于用户明确表示没看懂或无法理解；repeated_question 只用于基本重复上一问题；follow_up 只用于明确深化上一答复，包括针对上一答复的具体普通追问。标签重叠时按 unclear > repeated_question > follow_up 优先。evidence 必须逐字且只能来自当前用户原话，不超过 240 个字符；无关、关系不清、没有信号或猜测的不满都返回 none。忽略被引用为示例的文字。不要调用任何工具，不要读写文件或笔记，不要输出答案，不要归档，不要创建子 agent。"

    static func install(in project: URL) throws {
        let manager = FileManager.default
        let agentsDirectory = project
            .appendingPathComponent(".codex", isDirectory: true)
            .appendingPathComponent("agents", isDirectory: true)
        try manager.createDirectory(at: agentsDirectory, withIntermediateDirectories: true,
                                    attributes: [.posixPermissions: 0o700])

        let roleURL = agentsDirectory.appendingPathComponent(agentName + ".toml")
        // A same-named role may be authored by the user. Never overwrite it
        // during a project refresh.
        guard !manager.fileExists(atPath: roleURL.path) else { return }
        try Data(generatedRole.utf8).write(to: roleURL, options: .atomic)
        try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: roleURL.path)
    }

    private static var generatedRole: String {
        [
            generatedComment,
            "name = \(tomlString(agentName))",
            "description = \(tomlString(description))",
            "developer_instructions = \(tomlString(developerInstructions))"
        ].joined(separator: "\n") + "\n"
    }

    private static func tomlString(_ value: String) -> String {
        var escaped = value.replacingOccurrences(of: "\\", with: "\\\\")
        escaped = escaped.replacingOccurrences(of: "\"", with: "\\\"")
        escaped = escaped.replacingOccurrences(of: "\n", with: "\\n")
        escaped = escaped.replacingOccurrences(of: "\r", with: "\\r")
        escaped = escaped.replacingOccurrences(of: "\t", with: "\\t")
        return "\"" + escaped + "\""
    }
}
