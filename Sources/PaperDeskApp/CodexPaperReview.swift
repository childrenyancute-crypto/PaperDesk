import Foundation

/// Installs the optional Codex reviewer used by PaperDesk reading projects.
///
/// The reviewer is deliberately configured through its instructions only. The
/// parent project owns the PaperDesk MCP binding, model choice, and permissions.
enum CodexPaperReview {
    static let agentName = "paperdesk-answer-reviewer"

    /// One self-contained AGENTS.md bullet for the main agent's delegation
    /// policy. Keep this as one bullet so it can be embedded in a managed
    /// instruction block without adding another heading or role config.
    static let instructions = [
        "- 回答文献问题时先给直接结论，再给必要的推导；首次使用时解释符号，把条件和出处放在它们支持的主张旁边。",
        "用户要求普通回答、基线或单 agent 自检时，主 agent 自己完成。遇到复杂推导、长答复、多条关键的带出处论断，或用户要求“独立复核”时，派生一个名为 \(agentName) 的子 agent，在独立上下文中复核（如果提供 fork_context，则设为 false）。",
        "传给复核者原问题、暂定答复、固定的 snapshot_id 和带位置的拟用证据。复核者用 get_reading_snapshot 读取同一快照；工具不可用时只用已给的证据，并报告证据缺口。",
        "复核者检查内部矛盾、推导条件、每个关键论断旁的原文标记是否对应所给证据、未标注的论文转述，以及是否把论文的参考文献误当成已核读来源，只返回证据、影响及建议修改，不编号、不改写记录、不再派生子 agent。主 agent 等待并核验复核意见，保留正确且具体的主张，由主 agent 为实际使用的出处编号并归档一次完整答案；不能确认出处时将疑点写入 citation_warnings，不要猜测。复核者不可用时，如实说明。"
    ].joined(separator: " ")

    private static let generatedComment = "# paperdesk-managed: \(agentName) v1 (generated by PaperDesk)"
    private static let description = "复核理论物理与数学文献答复的正确性、证据范围和可读性"
    private static let developerInstructions = "你是 \(agentName)，负责复核理论物理和数学文献问题的拟答复。主 agent 会提供原问题、暂定答复、稳定的 snapshot_id，以及带页码、区段或其他位置的拟用证据；只使用这些输入。若可用，调用 get_reading_snapshot 读取同一 snapshot_id，不要重新 capture_reading_state；若工具不可用，使用已提供证据并明确报告缺失来源，绝不猜测。逐项检查关键论断旁是否有原文出处、编号是否指向支持该论断的给定段落、是否遗漏了依赖论文的段落，并区分论文自己的表述、论文引用的工作和回答者的推导。不能从所给资料验证的内容列为疑点，不要把书目元数据核实说成原始论文已支持该论断。检查内部矛盾、缺失假设、条件是否靠近主张、符号是否定义、是否有不必要的绕路。只返回简短的证据、影响和建议修改，保留正确且具体的主张。不要写入文件或笔记，不要调用 cite_passage、save_discussion 或其他写入、引用、归档操作，不要创建子 agent；引用和归档由主 agent 在核验后完成。"

    static func install(in project: URL) throws {
        let manager = FileManager.default
        let agentsDirectory = project
            .appendingPathComponent(".codex", isDirectory: true)
            .appendingPathComponent("agents", isDirectory: true)
        try manager.createDirectory(at: agentsDirectory, withIntermediateDirectories: true,
                                    attributes: [.posixPermissions: 0o700])

        let roleURL = agentsDirectory.appendingPathComponent(agentName + ".toml")
        guard !manager.fileExists(atPath: roleURL.path) else { return }
        try Data(generatedRole.utf8).write(to: roleURL, options: .atomic)
    }

    private static var generatedRole: String {
        [
            generatedComment,
            "name = \(tomlString(agentName))",
            "description = \(tomlString(description))",
            "developer_instructions = \(tomlString(developerInstructions))"
        ].joined(separator: "\n") + "\n"
    }

    private static func tomlString(_ value: String) -> String {
        var escaped = value.replacingOccurrences(of: "\\", with: "\\\\")
        escaped = escaped.replacingOccurrences(of: "\"", with: "\\\"")
        escaped = escaped.replacingOccurrences(of: "\n", with: "\\n")
        escaped = escaped.replacingOccurrences(of: "\r", with: "\\r")
        escaped = escaped.replacingOccurrences(of: "\t", with: "\\t")
        return "\"" + escaped + "\""
    }
}
